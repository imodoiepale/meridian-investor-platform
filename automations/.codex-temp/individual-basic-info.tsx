const flattenHistoryRecord = (record, basePath = '') => {
  let flattened = {};
  for (const key in record) {
    if (!record.hasOwnProperty(key) || key === 'updated_at') continue;
    const newPath = basePath ? `${basePath}.${key}` : key;
    const value = record[key];
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      Object.assign(flattened, flattenHistoryRecord(value, newPath));
    } else if (hasValue(value)) {
      const label = historyFieldLabelMap[newPath] || newPath.replace(/_/g, ' ');
      flattened[label] = value;
    }
  }
  return flattened;
};

