const renderFieldInput = (
  field: FormField,
  value: any,
  formData: Record<string, any>,
  handleChange: (fieldPath: string, value: any) => void,
  isDisabled: boolean,
  masterFieldsOptions: Record<string, any[]>,
  dependentOptions: Record<string, any[]> = {}
) => {
  const fieldPath = field.dataPath || field.name;
  const isAutoGenerated = isAutoField(field);
  const isLocked = isDisabled || isAutoGenerated;
  const lockReason = isAutoGenerated
    ? 'Locked: this field is auto-generated and cannot be edited.'
    : 'Locked: switch to Edit Mode to update this field.';

  let displayValue = value;
  if (isAutoGenerated) {
    displayValue = getAutoGeneratedValue(field.name, formData) || value;
  }

  const hasData = hasValue(displayValue);
  const emptyViewText = isAutoGenerated ? 'Auto-generated (read-only)' : 'missing';

  const commonInputClass = cn(
    "w-full transition-all duration-200 rounded-lg h-10 text-sm",
    hasData ? "bg-blue-50" : "bg-white",
    isLocked
      ? "bg-transparent border-transparent shadow-none cursor-default focus:ring-0 focus-visible:ring-0 focus-visible:ring-offset-0"
      : "border-gray-200 focus:border-blue-400 focus:ring-2 focus:ring-blue-100 shadow-sm",
    isLocked && !hasData && "text-red-500"
  );

  if (isAutoGenerated) {
    return (
      <Input
        type="text"
        value={hasData ? displayValue : (isLocked ? 'Auto-generated when data is available' : '')}
        placeholder={field.placeholder}
        disabled
        readOnly
        className={cn(
          commonInputClass,
          "bg-gradient-to-r from-blue-50 to-indigo-50 border-blue-200 text-blue-700 cursor-not-allowed",
          !hasData && isLocked && "text-blue-500 italic text-sm"
        )}
        title="Locked: this field is auto-generated from other form fields."
      />
    );
  }

  let options: { value: string; label: string }[] = [];
  if (field.name in dependentOptions) {
    options = dependentOptions[field.name] || [];
  } else if (field.dataSource?.category) {
    const categoryData = masterFieldsOptions[field.dataSource.category] || [];
    options = categoryData.map(opt => ({
      value: String(opt.value),
      label: opt.label || opt.value,
    }));
  } else if (field.staticOptions === 'genderOptions') {
    options = genderOptions;
  }

  switch (field.type) {
    case 'select': {
      const selectedOption = options.find((opt) =>
        String(opt.value).toLowerCase() === String(value ?? '').toLowerCase() ||
        String(opt.label).toLowerCase() === String(value ?? '').toLowerCase()
      );
      const selectedValue = selectedOption ? selectedOption.value : '';
      const hasNoOptions = options.length === 0;

      if (isLocked) {
        let selectDisplayValue = emptyViewText;
        if (hasData) {
          selectDisplayValue = selectedOption
            ? (selectedOption.label || selectedOption.value)
            : value || emptyViewText;
        } else if (hasNoOptions) {
          selectDisplayValue = "No options available";
        }
        return (
          <Input
            type="text"
            value={selectDisplayValue}
            readOnly
            title={lockReason}
            className={cn(commonInputClass, hasNoOptions && !hasData && "text-red-500")}
          />
        );
      }

      return (
        <SearchableSelect
          value={selectedValue}
          onValueChange={(newValue) => handleChange(fieldPath, newValue)}
          options={options}
          placeholder={hasNoOptions ? "No options available" : (field.placeholder || `Select ${field.label.toLowerCase()}`)}
          disabled={field.disabled || hasNoOptions}
          emptyMessage={hasNoOptions ? "No options available" : `No ${field.label.toLowerCase()} found.`}
          searchPlaceholder={`Search ${field.label.toLowerCase()}...`}
          buttonClassName={cn(commonInputClass, (!selectedValue || hasNoOptions) && "text-muted-foreground")}
          popoverClassName="w-[var(--radix-popover-trigger-width)]"
        />
      );
    }
    case 'date':
      if (isLocked) {
        return (
          <div className="relative">
            <Input
              type="text"
              value={hasData ? new Date(value).toLocaleDateString() : emptyViewText}
              readOnly
              title={lockReason}
              className={cn(commonInputClass, 'pl-10')}
            />
            <CalendarIcon className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-gray-400" />
          </div>
        );
      }
      const dateValue = new Date(value);
      const formattedDate = value && !isNaN(dateValue.getTime()) ? dateValue.toISOString().split('T')[0] : '';
      return (
        <div className="relative">
          <Input type="date" value={formattedDate} onChange={(e) => handleChange(fieldPath, e.target.value)} disabled={field.disabled} className={cn(commonInputClass, 'pl-10')} />
          <CalendarIcon className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-gray-400" />
        </div>
      );
    default:
      return (
        <Input
          type={field.type || 'text'}
          value={isLocked && !hasData ? emptyViewText : (value || '')}
          placeholder={isLocked ? '' : (field.placeholder || `Enter ${field.label.toLowerCase()}...`)}
          onChange={(e) => handleChange(fieldPath, e.target.value)}
          readOnly={isLocked}
          disabled={field.disabled || isAutoGenerated}
          title={isLocked ? lockReason : undefined}
          className={commonInputClass}
        />
      );
  }
};

