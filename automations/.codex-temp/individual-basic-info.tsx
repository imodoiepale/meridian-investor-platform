  const applyAutoFieldProtection = async (
    worksheet: ExcelJS.Worksheet,
    fields: FormField[],
    fieldRowMap: Record<string, number>
  ) => {
    const lockNote = 'Locked: this field is auto-generated and cannot be edited.';

    fields.forEach((field) => {
      const rowNum = fieldRowMap[field.name];
      if (!rowNum) return;

      const valueCell = worksheet.getCell(rowNum, 7);
      const autoLocked = isAutoField(field);

      valueCell.protection = { locked: autoLocked };
      if (autoLocked) {
        valueCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: EXCEL_COLORS.autoBg } };
        valueCell.note = lockNote;
      }
    });

    await worksheet.protect('auto-generated-lock', {
      selectLockedCells: true,
      selectUnlockedCells: true,
      formatCells: false,
      formatColumns: false,
      formatRows: false,
      insertColumns: false,
      insertRows: false,
      insertHyperlinks: false,
      deleteColumns: false,
      deleteRows: false,
      sort: false,
      autoFilter: false,
      pivotTables: false,
    });
  };

  const handleDownloadTemplate = async () => {
    try {
      const workbook = new ExcelJS.Workbook();
      const worksheet = workbook.addWorksheet('Import Template');
      const dataSheet = workbook.addWorksheet('DropdownLists');
      dataSheet.state = 'hidden';

      const { optionsMap } = await fetchAllDropdownOptions(allFields);
      prepareSheetBase(worksheet, 'INDIVIDUAL DATA IMPORT TEMPLATE', 'NEW INDIVIDUAL');

      const fieldsBySection = allFields.reduce((acc, field) => {
        (acc[field.section] = acc[field.section] || []).push(field);
        return acc;
      }, {});

      let currentRow = 5;
      const fieldRowMap: Record<string, number> = {};

      Object.entries(fieldsBySection).forEach(([sectionName, fields]: [string, any]) => {
        fields.forEach((field, index) => {
          fieldRowMap[field.name] = currentRow;
          const row = worksheet.getRow(currentRow);
          row.values = [field.id, sectionName, field.label, field.fieldType || field.type || 'text', isAutoField(field) ? 'Auto' : 'Manual', field.source || 'Client', ''];

          row.eachCell({ includeEmpty: true }, (cell, colNum) => {
            const customStyle: any = {};
            if (index === 0) customStyle.border = { top: { style: 'medium', color: { argb: EXCEL_COLORS.headerBg } } };
            if (colNum === 7) customStyle.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: EXCEL_COLORS.valueBg } };
            styleCell(cell, customStyle);
          });

          currentRow++;
        });
      });

      applyIndividualAddressFormulas(worksheet, fieldRowMap);

      let listCol = 1;
      allFields.forEach((field) => {
        const rowNum = fieldRowMap[field.name];
        if (!rowNum || field.type !== 'select' || isAutoField(field)) return;

        const optData = optionsMap[field.name];
        const colLetter = dataSheet.getColumn(listCol).letter;

        if (!optData || optData.allOptions.length === 0) {
          dataSheet.getCell(1, listCol).value = "No options found";
          worksheet.getCell(rowNum, 7).dataValidation = { type: 'list', formulae: [`DropdownLists!$${colLetter}$1:$${colLetter}$1`] };
        } else if (optData.type === 'standard') {
          optData.allOptions.forEach((option, index) => {
            dataSheet.getCell(index + 1, listCol).value = option.label;
          });
          worksheet.getCell(rowNum, 7).dataValidation = { type: 'list', formulae: [`DropdownLists!$${colLetter}$1:$${colLetter}$${optData.allOptions.length}`] };
        } else if (optData.type === 'dependent') {
          const parentRow = fieldRowMap[optData.parentFieldName || ''];
          if (parentRow) {
            Object.entries(optData.manualMapping || {}).forEach(([parentId, children]: [string, any], mappingIndex) => {
              const start = (mappingIndex * 500) + 1;
              const parentLabel = optData.parentValueToLabelMap?.[parentId] || parentId;
              const rangeName = `TMPVAL_${toSafeRangeName(field.name)}_${toSafeRangeName(parentLabel)}`;
              children.forEach((child, childIndex) => {
                dataSheet.getCell(start + childIndex, listCol).value = child.label || child.name || child.value;
              });
              workbook.definedNames.add(`DropdownLists!$${colLetter}$${start}:$${colLetter}$${start + children.length - 1}`, rangeName);
            });
            worksheet.getCell(rowNum, 7).dataValidation = {
              type: 'list',
              allowBlank: true,
              formulae: [`=INDIRECT("TMPVAL_${toSafeRangeName(field.name)}_"&${buildExcelSafeSubstitute(`$G$${parentRow}`)})`],
              showErrorMessage: false
            };
          }
        }

        listCol++;
      });

      await applyAutoFieldProtection(worksheet, allFields, fieldRowMap);

      const buffer = await workbook.xlsx.writeBuffer();
      saveAs(new Blob([buffer]), `Individual_Basic_Info_Template.xlsx`);
      toast.success("Template downloaded!");
    } catch (downloadError) {
      console.error("[Template] Error:", downloadError);
      toast.error("Template failed");
    }
  };

  const handleImportExcel = async (event: React.ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    if (!file) return;

    const loadingToast = toast.loading("Parsing Excel file...");
    setUploading(true);

    try {
      const workbook = new ExcelJS.Workbook();
      const arrayBuffer = await file.arrayBuffer();
      await workbook.xlsx.load(arrayBuffer);
      const worksheet = workbook.getWorksheet(1);
      if (!worksheet) throw new Error('No worksheet found in file.');

      const getVal = (cell: ExcelJS.Cell) => {
        if (!cell || cell.value === null || cell.value === undefined) return "";
        if (typeof cell.value === 'object') {
          return (cell.value as any).result || (cell.value as any).richText?.map((t: any) => t.text).join('') || (cell.value as any).text || "";
        }
        return String(cell.value).trim();
      };

      let headerRowIndex = -1;
      worksheet.eachRow((row, rowNumber) => {
        if (headerRowIndex !== -1) return;
        const col1 = getVal(row.getCell(1));
        const col3 = getVal(row.getCell(3));
        if (col1 === '#' || col3 === 'Field') {
          headerRowIndex = rowNumber;
        }
      });

      if (headerRowIndex === -1) {
        throw new Error('Invalid template header. Please use the exported template.');
      }

      const nextFormData = JSON.parse(JSON.stringify(formData));
      const headerRow = worksheet.getRow(headerRowIndex);
      const isRowWise = getVal(headerRow.getCell(3)) === 'Field';

      if (isRowWise) {
        for (let rowIndex = headerRowIndex + 1; rowIndex <= worksheet.rowCount; rowIndex++) {
          const row = worksheet.getRow(rowIndex);
          const label = getVal(row.getCell(3));
          const value = getVal(row.getCell(7));
          if (!label) continue;

          const field = allFields.find((candidate) => candidate.label === label);
          if (!field || isAutoField(field)) continue;
          syncFieldValue(nextFormData, field, value);
        }
      } else {
        const headerMap: Record<string, number> = {};
        headerRow.eachCell((cell, colNumber) => {
          const label = getVal(cell);
          if (label) headerMap[label] = colNumber;
        });

        const dataRow = worksheet.getRow(headerRowIndex + 1);
        if (!dataRow.hasValues) {
          throw new Error("No data found below the header row.");
        }

        allFields.forEach((field) => {
          const colNumber = headerMap[field.label.trim()];
          if (!colNumber || isAutoField(field)) return;
          syncFieldValue(nextFormData, field, getVal(dataRow.getCell(colNumber)));
        });
      }

      const residentialAddress = generateFullResidentialAddress(nextFormData);
      const postalAddress = generateFullPostalAddress(nextFormData);
      nextFormData.full_residential_address = residentialAddress;
      nextFormData.full_postal_address = postalAddress;
      set(nextFormData, 'residential_address_details.full_residential_address', residentialAddress);
      set(nextFormData, 'residential_address_details.current.full_residential_address', residentialAddress);
      set(nextFormData, 'residential_address_details.current.full_address', residentialAddress);
      set(nextFormData, 'postal_address_details.current.full_postal_address', postalAddress);

      setFormData(nextFormData);
      toast.success("Data imported successfully!", { id: loadingToast });
    } catch (importError: any) {
      console.error("[Import] Error:", importError);
      toast.error(`Import failed: ${importError.message}`, { id: loadingToast });
    } finally {
      setUploading(false);
      if (fileInputRef.current) fileInputRef.current.value = '';
    }
  };

