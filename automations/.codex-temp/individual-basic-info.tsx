  const handleExportImage = async (format: 'png' | 'jpeg' | 'pdf') => {
    setIsExporting(true);
    await new Promise(resolve => setTimeout(resolve, 50));
    const exportElement = document.getElementById('export-container');
    if (!exportElement) {
      setIsExporting(false);
      return;
    }
    const canvas = await html2canvas(exportElement, { scale: 2 });
    if (format === 'pdf') {
      const imgData = canvas.toDataURL('image/png');
      const pdf = new jsPDF('p', 'mm', 'a4');
      const pdfWidth = pdf.internal.pageSize.getWidth();
      const pdfHeight = (canvas.height * pdfWidth) / canvas.width;
      pdf.addImage(imgData, 'PNG', 0, 0, pdfWidth, pdfHeight);
      pdf.save(`${localIndividual.full_name}_Info.pdf`);
    } else {
      const image = canvas.toDataURL(`image/${format}`, 1.0);
      const link = document.createElement('a');
      link.href = image;
      link.download = `${localIndividual.full_name}_Info.${format}`;
      link.click();
    }
    setIsExporting(false);
  };

